from datetime import datetime


def _get_matrix_validation_rule(user_data: dict) -> str:
    """Генерирует правило валидации матрицы энергии для промптов."""
    matrix_energies = user_data.get('matrix_energies', {})
    
    # Создаем список энергий пользователя
    energy_list = []
    for energy_key, energy_value in matrix_energies.items():
        energy_list.append(f"{energy_key}: {energy_value}")
    
    energy_list_str = "\n".join(energy_list) if energy_list else "Матрица пуста"
    
    return f"""
╔════════════════════════════════════════════════════════════╗
║  🚨 КРИТИЧЕСКОЕ ПРАВИЛО - МАТРИЦА ЭНЕРГИЙ 🚨             ║
╠════════════════════════════════════════════════════════════╣
║  ИСПОЛЬЗУЙ ТОЛЬКО энергии из матрицы ниже!                ║
║  НИКОГДА не приписывай энергии, которых НЕТ в матрице!   ║
╚════════════════════════════════════════════════════════════╝

Примеры ПРАВИЛЬНОГО использования:
✅ Если в матрице есть "Энергия 3" → можно описать её
❌ Если в матрице НЕТ "Энергия 4" → НЕЛЬЗЯ говорить "креативность"

Матрица пользователя:
{energy_list_str}

Перед описанием ЛЮБОЙ энергии - ПРОВЕРЬ её наличие в списке выше!
"""


