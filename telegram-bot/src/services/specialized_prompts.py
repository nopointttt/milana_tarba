    @classmethod
    def get_prompt_by_type(cls, query_type: str, user_data: dict) -> str:
        """Возвращает промпт для указанного типа запроса."""
        
        prompt_methods = {
            "FINANCE": cls.get_finance_prompt,
            "TIME": cls.get_time_prompt,
            "RELATIONSHIPS": cls.get_relationships_prompt,
            "REALIZATION": cls.get_realization_prompt,
            "HEALTH": cls.get_health_prompt,
            "GENERAL": cls.get_general_prompt
        }
        
        method = prompt_methods.get(query_type, cls.get_general_prompt)
        return method(user_data)
