"""src/services/query_classifier.py
Классификация запросов пользователей по типам.
"""
from typing import Dict, List, Any
from openai import AsyncOpenAI


class QueryClassifier:
    """Классификатор запросов пользователей."""
    
    def __init__(self, api_key: str):
        """Инициализировать классификатор."""
        self.client = AsyncOpenAI(api_key=api_key)
        
        # Определения типов запросов
        self.query_types = {
            "FINANCE": "Финансы, деньги, заработок, карьера, бизнес, материальное благополучие",
            "TIME": "Время, прогнозы, когда что-то делать, временные рекомендации",
            "RELATIONSHIPS": "Отношения, любовь, семья, совместимость, партнерство",
            "REALIZATION": "Реализация, предназначение, таланты, саморазвитие, цели",
            "HEALTH": "Здоровье, самочувствие, энергия, физическое состояние",
            "ENERGY_RECOVERY": "Восстановление энергии, усталость, истощение, подпитка, источники энергии",
            "RELATIONSHIP_LIFEHACKS": "Лайфхаки в отношениях, как общаться, стратегии по ЧС",
            "TRIGGERS": "Триггеры, раздражители, что злит, конфликты, что выводит из себя",
            "KARMA": "Карма, кармические задачи, предназначение, жизненные уроки, Дхарма",
            "TRANSFORMATION": "Трансформация сознания, развитие личности, расширение сознания",
            "GENERAL": "Общие вопросы о цифрологии, теории, объяснения"
        }
    
    async def classify_query(self, user_message: str) -> str:
        """Классифицирует запрос пользователя.
        
        :param user_message: Сообщение пользователя
        :return: Тип запроса (FINANCE, TIME, RELATIONSHIPS, REALIZATION, HEALTH, GENERAL)
        """
        try:
            # Создаем промпт для классификации
            classification_prompt = self._get_classification_prompt()
            
            # Отправляем запрос в OpenAI
            response = await self.client.chat.completions.create(
                model="gpt-4o",
                messages=[
                    {"role": "system", "content": classification_prompt},
                    {"role": "user", "content": f"Вот запрос: {user_message}"}
                ],
                temperature=0.1,  # Низкая температура для более точной классификации
                max_tokens=10
            )
            
            # Извлекаем результат (ожидаем число от 1 до 11)
            result = response.choices[0].message.content.strip()
            
            # Преобразуем число в тип запроса
            type_mapping = {
                "1": "FINANCE",
                "2": "TIME", 
                "3": "RELATIONSHIPS",
                "4": "REALIZATION",
                "5": "HEALTH",
                "6": "ENERGY_RECOVERY",
                "7": "RELATIONSHIP_LIFEHACKS",
                "8": "TRIGGERS",
                "9": "KARMA",
                "10": "TRANSFORMATION",
                "11": "GENERAL"
            }
            
            # Валидируем результат
            if result in type_mapping:
                return type_mapping[result]
            else:
                # Если результат не распознан, возвращаем GENERAL
                return "GENERAL"
                
        except Exception as e:
            print(f"Ошибка классификации запроса: {e}")
            return "GENERAL"
    
    def _get_classification_prompt(self) -> str:
        """Создает промпт для классификации запроса."""
        
        return """Ты - классификатор запросов для бота по цифрологии.

Твоя задача: определить тип запроса пользователя из следующих категорий:

1. FINANCE - Финансы, деньги, заработок, карьера, бизнес, материальное благополучие
2. TIME - Время, прогнозы, когда что-то делать, временные рекомендации
3. RELATIONSHIPS - Отношения, любовь, семья, совместимость, партнерство
4. REALIZATION - Реализация, предназначение, таланты, саморазвитие, цели
5. HEALTH - Здоровье, самочувствие, энергия, физическое состояние
6. ENERGY_RECOVERY - Восстановление энергии, усталость, истощение, подпитка, источники энергии
7. RELATIONSHIP_LIFEHACKS - Лайфхаки в отношениях, как общаться, стратегии по ЧС
8. TRIGGERS - Триггеры, раздражители, что злит, конфликты, что выводит из себя
9. KARMA - Карма, кармические задачи, предназначение, жизненные уроки, Дхарма
10. TRANSFORMATION - Трансформация сознания, развитие личности, расширение сознания
11. GENERAL - Общие вопросы о цифрологии, теории, объяснения

ПРАВИЛА КЛАССИФИКАЦИИ:
- Отвечай ТОЛЬКО цифрой от 1 до 11
- Если запрос содержит несколько тем - выбери наиболее выраженную
- Если не уверен - выбери 6 (GENERAL)
- Если запрос о времени, прогнозах, "когда" - выбери 2
- Если запрос о деньгах, работе, карьере - выбери 1
- Если запрос о отношениях, любви, семье - выбери 3
- Если запрос о развитии, талантах, целях, ПРАКТИКАХ - выбери 4
- Если запрос о здоровье, физическом состоянии - выбери 5
- Если запрос об УСТАЛОСТИ, восстановлении ЭНЕРГИИ - выбери 6
- Если запрос о ЛАЙФХАКАХ в отношениях, как общаться - выбери 7
- Если запрос о РАЗДРАЖИТЕЛЯХ, что злит, конфликты - выбери 8
- Если запрос о КАРМЕ, жизненных уроках, духовных задачах - выбери 9
- Если запрос о ТРАНСФОРМАЦИИ, развитии сознания - выбери 10
- ВАЖНО: "практика", "упражнение" = всегда выбирай 4 (REALIZATION)

Примеры:
- "Как мне заработать больше денег?" → 1
- "Когда лучше начать бизнес?" → 2
- "Помоги с отношениями" → 3
- "Какое мое предназначение?" → 4
- "Дай практику по личному году" → 4
- "Что делать для здоровья?" → 5
- "Я устал, как восстановить энергию?" → 6
- "Лайфхаки для общения с партнером" → 7
- "Что меня раздражает?" → 8
- "Мои кармические задачи" → 9
- "Как развивать сознание?" → 10
- "Что такое ЧС?" → 11

Ответ:"""
